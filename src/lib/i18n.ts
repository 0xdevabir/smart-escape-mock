export const dictionaries: Record<Lang, Dict> = { en, bn }

const BN_DIGITS = '০১২৩৪৫৬৭৮৯'
export const formatNum = (n: number | string, lang: Lang) =>
  lang === 'bn' ? String(n).replace(/[0-9]/g, (d) => BN_DIGITS[+d]) : String(n)

export function translate(lang: Lang, key: string, params?: Record<string, string | number>) {
  const s = dictionaries[lang][key] ?? dictionaries.en[key] ?? key
  if (!params) return s
  // Numbers get localized digits; strings (IDs, dataset labels) are left as-is.
  return s.replace(/\{(\w+)\}/g, (_, k) => {
    const v = params[k]
    return v === undefined ? `{${k}}` : typeof v === 'number' ? formatNum(v, lang) : v
  })
}
